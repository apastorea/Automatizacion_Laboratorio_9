% VERIFICAR_FIRMWARE_LAB9 Contrasta las constantes C con el diseno MATLAB.

clearvars;
clc;

carpetaModelo = fileparts(mfilename("fullpath"));
rutaFuente = fullfile(carpetaModelo, "..", "02_Firmware_PSoC_5LP", ...
    "src", "lab9_control_optimo.c");
rutaConfig = fullfile(carpetaModelo, "..", "02_Firmware_PSoC_5LP", ...
    "src", "lab9_config.h");
rutaWorkspace = fullfile(carpetaModelo, "..", "02_Firmware_PSoC_5LP", ...
    "PSoC_Creator_Lab9");
rutaProyecto = fullfile(rutaWorkspace, "Lab9.cydsn");

fuente = fileread(rutaFuente);
configuracion = fileread(rutaConfig);

% Las expresiones regulares extraen las tres realizaciones numericas grabadas
% en C sin ejecutar ni reinterpretar el firmware.
kx1C = extraerValores(fuente, ...
    'p->Kx\[0\]\s*=\s*([-+0-9.eE]+)f;');
kx2C = extraerValores(fuente, ...
    'p->Kx\[1\]\s*=\s*([-+0-9.eE]+)f;');
kiC = extraerValores(fuente, ...
    'p->Ki\s*=\s*([-+0-9.eE]+)f;');

assert(numel(kx1C) == 3 && numel(kx2C) == 3 && numel(kiC) == 3, ...
    "No se encontraron exactamente tres juegos de ganancias en C.");

% Se reconstruye el modelo identificado y se recalcula dlqr; esto evita una
% comparacion circular contra un archivo de resultados previamente generado.
Ts = 0.002;
C = [0, 1];
R5 = 150e3;
R6 = 47e3;
Kid = 1.002941;
tau1 = 0.00906915;
tau2 = 0.000774399;
gananciaEtapa1 = R5/R6;
gananciaEtapa2 = Kid/gananciaEtapa1;
Fid = [-1/tau1, 0; -gananciaEtapa2/tau2, -1/tau2];
Gid = [-gananciaEtapa1/tau1; 0];
[A, B, ~, ~] = ssdata(c2d(ss(Fid, Gid, C, 0), Ts, "zoh"));
Aaug = [A, zeros(2,1); -C, 1];
Baug = [B; 0];

Qs = {diag([0.01, 0.01, 0.001]), ...
      diag([0.01, 0.01, 0.1]), ...
      diag([0.01, 0.01, 0.001])};
Rs = [1, 0.1, 0.01];

gananciasMatlab = zeros(3,3);
for i = 1:3
    gananciasMatlab(i,:) = dlqr(Aaug, Baug, Qs{i}, Rs(i));
end
gananciasC = [kx1C, kx2C, kiC];
errores = abs(gananciasC-gananciasMatlab);

% El firmware utiliza float de 32 bits; la tolerancia contempla el redondeo.
assert(max(errores, [], "all") < 5e-7, ...
    "Las ganancias C no coinciden con dlqr.");
assert(contains(configuracion, ...
    "#define LAB9_MODO                  LAB9_MODO_MONITOR"), ...
    "El firmware no queda en MONITOR por defecto.");
enclavamientosSeguros = [ ...
    "#define LAB9_AUTORIZAR_ESCALON         (0u)", ...
    "#define LAB9_PLANTA_VERIFICADA         (0u)", ...
    "#define LAB9_ADC_DAC_REVALIDADOS       (0u)", ...
    "#define LAB9_AUTORIZAR_LAZO_CERRADO   (0u)"];
assert(all(arrayfun(@(texto) contains(configuracion, texto), ...
    enclavamientosSeguros)), ...
    "Revisar enclavamientos seguros de la configuracion.");

% La copia de trabajo de PSoC Creator debe ser byte a byte identica a las
% fuentes canonicas para que el HEX compilado sea auditable.
archivosSincronizados = [ ...
    "lab9_config.h", "lab9_control_optimo.c", "lab9_control_optimo.h", ...
    "lab9_hardware.c", "lab9_hardware.h", "lab9_telemetria.c", ...
    "lab9_telemetria.h", "lab9_types.h", "lab9_version.h"];
for archivo = archivosSincronizados
    origen = fullfile(carpetaModelo, "..", "02_Firmware_PSoC_5LP", ...
        "src", archivo);
    destino = fullfile(rutaProyecto, archivo);
    assert(isfile(destino) && strcmp(fileread(origen), fileread(destino)), ...
        "El workspace PSoC no esta sincronizado: %s", archivo);
end
assert(strcmp(fileread(fullfile(carpetaModelo, "..", ...
    "02_Firmware_PSoC_5LP", "src", "lab9_main_psoc.c")), ...
    fileread(fullfile(rutaProyecto, "main.c"))), ...
    "El main.c del workspace PSoC no esta sincronizado.");
assert(isfile(fullfile(rutaWorkspace, "Lab9.cywrk")), ...
    "No se encontro el workspace Lab9.cywrk.");
assert(isfile(fullfile(rutaProyecto, "Lab9.cyprj")), ...
    "No se encontro el proyecto Lab9.cyprj.");
assert(isfile(fullfile(rutaProyecto, "CortexM3", "ARM_GCC_541", ...
    "Release", "Lab9.hex")), ...
    "No se encontro el binario Lab9.hex compilado.");

caso = (1:3)';
errorKx1 = errores(:,1);
errorKx2 = errores(:,2);
errorKi = errores(:,3);
verificacion = table(caso, kx1C, kx2C, kiC, ...
    gananciasMatlab(:,1), gananciasMatlab(:,2), gananciasMatlab(:,3), ...
    errorKx1, errorKx2, errorKi, ...
    'VariableNames', {'caso','Kx1_C','Kx2_C','Ki_C', ...
    'Kx1_MATLAB','Kx2_MATLAB','Ki_MATLAB', ...
    'error_Kx1','error_Kx2','error_Ki'});
disp(verificacion);

rutaSalida = fullfile(carpetaModelo, "..", "05_Resultados", ...
    "verificacion_firmware_lab9.csv");
writetable(verificacion, rutaSalida);
fprintf("Ganancias C verificadas contra dlqr. Maximo error: %.3e\n", ...
    max(errores, [], "all"));
fprintf("Configuracion segura verificada: MONITOR y enclavamientos en cero.\n");
fprintf("Workspace Lab9 sincronizado y binario Release presente.\n");

function valores = extraerValores(texto, patron)
    tokens = regexp(texto, patron, 'tokens');
    valores = cellfun(@(token) str2double(token{1}), tokens(:));
end
